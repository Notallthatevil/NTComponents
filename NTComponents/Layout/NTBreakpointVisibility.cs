namespace NTComponents;

/// <summary>
///     Defines whether responsive content is shown or hidden on the targeted side of a breakpoint.
/// </summary>
public enum NTBreakpointVisibility {

    /// <summary>
    ///     Shows the content on the targeted side of the breakpoint and hides it on the other side.
    /// </summary>
    Show,

    /// <summary>
    ///     Hides the content on the targeted side of the breakpoint and shows it on the other side.
    /// </summary>
    Hide
}
