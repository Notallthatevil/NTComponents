namespace NTComponents;

/// <summary>
///     Defines the Material 3 viewport-width thresholds used by responsive components.
/// </summary>
public enum NTBreakpoint {

    /// <summary>
    ///     The 600 pixel threshold between compact and small layouts.
    /// </summary>
    Small = 600,

    /// <summary>
    ///     The 840 pixel threshold between small and medium layouts.
    /// </summary>
    Medium = 840,

    /// <summary>
    ///     The 1200 pixel threshold between medium and large layouts.
    /// </summary>
    Large = 1200,

    /// <summary>
    ///     The 1600 pixel threshold between large and extra-large layouts.
    /// </summary>
    ExtraLarge = 1600
}
